/**
 * ITM path-loss scalar model — a faithful port of the MeshCore-analytics
 * link-budget model (reference: `ukmesh-planner-work/reference/loss.py`,
 * `compute_path_loss_from_profile` ~lines 282–350 and the sampling convention
 * in `compute_path_loss` ~lines 223–267; constants from `rf/config.py`).
 *
 * WHY a port rather than reuse of the planner's own Deygout/FSPL code: the
 * live analytics system's neighbour-link numbers are what operators see on
 * the mesh map, so planner-computed links must reproduce *its* numbers —
 * quirks included — and stay reproducible when it changes. This module
 * therefore keeps variable names, operation order and branch structure close
 * to the reference; places where the reference relies on NumPy semantics
 * (percentile interpolation, tie ordering) are called out in comments.
 *
 * Golden values: `itm.fixture.json`, generated by
 * `tools/parity/gen-itm-golden.py` running the (gdal-trimmed) reference code.
 *
 * Deliberate deviations from the reference, all documented here:
 * - the gdal-backed raster read is replaced by a caller-supplied
 *   `elevationAt` sampler, and the reference's float32 cast of the sampled
 *   profile (~line 274) is not reproduced — profiles stay float64 (the
 *   golden generator feeds float64 too);
 * - `PATH_LOSS_BIAS_DB` is fixed at 0 (env-var tuning is out of scope);
 * - the scalar reference does not return `max_v`, which the port exposes;
 *   where the reference returns before evaluating any interior point,
 *   `maxV` is the same -999 sentinel its prefix implementation
 *   (`compute_prefix_path_losses`) initialises `max_vs` to.
 */
import type { LatLon } from './geo.js';

/** 868 MHz wavelength, metres (reference `rf.config.LAMBDA_M`). */
export const ITM_LAMBDA_M = 3e8 / (868e6);

/** Effective earth radius factor (reference `rf.config.K_FACTOR`). */
export const ITM_K_FACTOR = 4 / 3;

/** True earth radius, metres (reference `rf.config.R_EARTH_M`). */
export const ITM_R_EARTH_M = 6_371_000;

/** Nominal profile sample spacing, metres (reference `rf.config.PROFILE_STEP_M`). */
export const ITM_PROFILE_STEP_M = 100;

/** Fresnel-parameter limit for "clear line of sight" (reference `rf.config.LINK_LOS_MAX_V`). */
export const ITM_LINK_LOS_MAX_V = 1.12;

/** Default usable path-loss threshold, dB (reference `rf.config.DEFAULT_USABLE_PATH_LOSS_DB`). */
export const DEFAULT_USABLE_PATH_LOSS_DB = 137.5;

/** Terrain-roughness coefficient (reference `loss.py` `TERRAIN_ROUGHNESS_FACTOR`). */
export const ITM_TERRAIN_ROUGHNESS_FACTOR = 0.08;

/** Path-loss bias (reference `PATH_LOSS_BIAS_DB`; env-var tuning not ported). */
export const ITM_PATH_LOSS_BIAS_DB = 0;

/** `maxV` sentinel: no interior point was evaluated (reference `-999.0`). */
export const ITM_NO_MAX_V = -999;

/** Elevation source for {@link sampleItmProfile}; returns metres ASL. */
export type ItmElevationSampler = (lat: number, lon: number) => number;

/** Sampled terrain profile: `dists` metres from endpoint A, `heights` metres ASL. */
export interface ItmProfile {
  dists: number[];
  heights: number[];
}

export interface ItmPathLossInput {
  /** Profile distances from the transmitter, metres (`dists = t · d_total`). */
  dists: readonly number[];
  /** Terrain heights ASL, metres — one per distance. */
  heights: readonly number[];
  /** Transmitter height ASL, metres (endpoint elevation + antenna height). */
  hTxM: number;
  /** Receiver height ASL, metres. */
  hRxM: number;
  /** Usable path-loss threshold, dB (reference `current_usable_path_loss_db()`). */
  usableThresholdDb?: number;
}

export interface ItmPathLossResult {
  pathLossDb: number;
  viable: boolean;
  /** Worst Fresnel parameter over the profile; {@link ITM_NO_MAX_V} when none evaluated. */
  maxV: number;
}

/** Green/amber/red band boundaries, dB (reference `RF_CALIBRATION['signal_thresholds_db']`). */
export function itmSignalThresholdsDb(
  usableThresholdDb: number = DEFAULT_USABLE_PATH_LOSS_DB,
): { green: number; amber: number; red: number } {
  return {
    green: Math.max(116, usableThresholdDb - 16),
    amber: Math.max(124, usableThresholdDb - 8),
    red: usableThresholdDb,
  };
}

export type ItmSignalBand = 'green' | 'amber' | 'red';

/**
 * Band a path loss for coverage display. The analytics front end draws
 * exactly three exclusive strength rings (red/amber/green, from
 * `build_exclusive_strength_geoms`), so losses at or above the amber
 * boundary fall in the outermost "red" band; losses past the usable
 * threshold are outside the coverage polygon entirely and the caller is
 * expected to drop them (see {@link ItmPathLossResult.viable}).
 */
export function itmSignalBand(
  pathLossDb: number,
  usableThresholdDb: number = DEFAULT_USABLE_PATH_LOSS_DB,
): ItmSignalBand {
  const t = itmSignalThresholdsDb(usableThresholdDb);
  if (pathLossDb < t.green) return 'green';
  if (pathLossDb < t.amber) return 'amber';
  return 'red';
}

/**
 * Sample the linear profile between two endpoints the way the reference
 * `compute_path_loss` does before calling the scalar model: equirectangular
 * distance (`dlat·111320`, `dlon·111320·cos(midlat)`), `n = clamp(floor(d/100),
 * 20, 200)` steps — so `n + 1` samples — positions by linear lat/lon
 * interpolation, heights via the caller's sampler with the reference's
 * sanitising (non-finite or outside [-500, 9000] → 0, then clamp ≥ 0).
 *
 * Sub-metre paths: the reference short-circuits to a single-point profile at
 * the transmitter, which the port reproduces by sampling endpoint A.
 */
export function sampleItmProfile(
  a: LatLon,
  b: LatLon,
  elevationAt: ItmElevationSampler,
): ItmProfile {
  const cosMid = Math.cos(((a.lat + b.lat) / 2) * (Math.PI / 180));
  const dLat = (b.lat - a.lat) * 111_320;
  const dLon = (b.lon - a.lon) * 111_320 * cosMid;
  const dTotal = Math.sqrt(dLat * dLat + dLon * dLon);

  if (dTotal < 1.0) {
    return { dists: [0.0], heights: [cleanHeight(elevationAt(a.lat, a.lon))] };
  }

  const n = Math.max(20, Math.min(200, Math.floor(dTotal / ITM_PROFILE_STEP_M)));
  const dists: number[] = [];
  const heights: number[] = [];
  for (let i = 0; i <= n; i += 1) {
    const t = i / n;
    const lat = a.lat + t * (b.lat - a.lat);
    const lon = a.lon + t * (b.lon - a.lon);
    dists.push(t * dTotal);
    heights.push(cleanHeight(elevationAt(lat, lon)));
  }
  return { dists, heights };
}

/** Reference sanitising: non-finite or outside [-500, 9000] → 0, then clamp ≥ 0. */
function cleanHeight(rawHeightM: number): number {
  const h =
    Number.isFinite(rawHeightM) && rawHeightM >= -500 && rawHeightM <= 9_000
      ? rawHeightM
      : 0.0;
  return Math.max(0, h);
}

/**
 * Scalar path-loss model — port of the reference
 * `compute_path_loss_from_profile` (loss.py ~282–350).
 *
 * Pipeline: drop non-finite samples, sort by distance; free-space loss for
 * the line-of-sight term; per-interior-point Fresnel parameter `v` against
 * the LOS chord, adjusted for the 4/3-earth bulge; knife-edge diffraction
 * from `max(v)`; a p75 terrain-roughness term; total =
 * `max(fspl, fspl + diffraction + roughness + bias)`.
 */
export function computeItmPathLoss(input: ItmPathLossInput): ItmPathLossResult {
  const { dists, heights, hTxM, hRxM } = input;
  const usableThresholdDb = input.usableThresholdDb ?? DEFAULT_USABLE_PATH_LOSS_DB;

  // Reference: `len(dists) != len(heights) or len(dists) == 0` → (+inf, False).
  if (dists.length !== heights.length || dists.length === 0) {
    return { pathLossDb: Number.POSITIVE_INFINITY, viable: false, maxV: ITM_NO_MAX_V };
  }

  // Reference: `finite = np.isfinite(dists) & np.isfinite(heights)`; fewer
  // than two finite samples → (+inf, False).
  const finite: ProfilePoint[] = [];
  for (let i = 0; i < dists.length; i += 1) {
    const d = dists[i]!;
    const h = heights[i]!;
    if (Number.isFinite(d) && Number.isFinite(h)) finite.push({ d, h });
  }
  if (finite.length < 2) {
    return { pathLossDb: Number.POSITIVE_INFINITY, viable: false, maxV: ITM_NO_MAX_V };
  }

  // Reference: `np.argsort(dists)` (quicksort — tie order unspecified);
  // Array.prototype.sort is stable. Tie order changes neither the
  // interior-point set nor anything else the model reads.
  finite.sort((p, q) => p.d - q.d);
  const dTotal = finite[finite.length - 1]!.d;

  // Reference: sub-metre paths return a flat zero-loss viable result.
  if (dTotal < 1.0) {
    return { pathLossDb: 0.0, viable: true, maxV: ITM_NO_MAX_V };
  }

  const fspl = 20 * Math.log10((4 * Math.PI * dTotal) / ITM_LAMBDA_M);

  // Two or fewer samples: FSPL only; viability comes from the threshold.
  if (finite.length <= 2) {
    return { pathLossDb: fspl, viable: fspl < usableThresholdDb, maxV: ITM_NO_MAX_V };
  }

  // Reference keeps interior points with strictly positive distances on both
  // sides (`d1 > 0 & d2 > 0`); with no valid interior it falls back to FSPL.
  const interior: Array<{ d1: number; h: number }> = [];
  for (let i = 1; i < finite.length - 1; i += 1) {
    const point = finite[i]!;
    const d1 = point.d;
    const d2 = dTotal - d1;
    if (d1 > 0 && d2 > 0) interior.push({ d1, h: point.h });
  }
  if (interior.length === 0) {
    return { pathLossDb: fspl, viable: fspl < usableThresholdDb, maxV: ITM_NO_MAX_V };
  }

  // Fresnel parameter per interior point; `max_v` drives the diffraction term.
  let maxV = Number.NEGATIVE_INFINITY;
  for (const { d1, h } of interior) {
    const d2 = dTotal - d1;
    const losH = hTxM + (hRxM - hTxM) * (d1 / dTotal);
    const earthBulgeM = (d1 * d2) / (2 * ITM_K_FACTOR * ITM_R_EARTH_M);
    const excessH = h + earthBulgeM - losH;
    const v = excessH * Math.sqrt((2 * (d1 + d2)) / (ITM_LAMBDA_M * d1 * d2));
    if (v > maxV) maxV = v;
  }

  let diffLoss = 0.0;
  if (maxV > -0.78) {
    diffLoss = Math.max(
      0.0,
      6.9 + 20 * Math.log10(Math.sqrt((maxV - 0.1) ** 2 + 1) + maxV - 0.1),
    );
  }

  // Reference roughness: NumPy p75 (linear interpolation) of |Δheight| over
  // the distance-sorted profile, only when there are more than three samples.
  const terrainRoughness = finite.length > 3 ? percentile75AbsHeightDiff(finite) : 0.0;
  const roughnessLoss = Math.min(
    6.0,
    Math.log1p(Math.max(0.0, terrainRoughness)) * ITM_TERRAIN_ROUGHNESS_FACTOR,
  );

  const totalLoss = Math.max(fspl, fspl + diffLoss + roughnessLoss + ITM_PATH_LOSS_BIAS_DB);
  const clearLos = maxV <= ITM_LINK_LOS_MAX_V;
  const viable = clearLos && totalLoss < usableThresholdDb;
  return { pathLossDb: totalLoss, viable, maxV };
}

interface ProfilePoint {
  d: number;
  h: number;
}

/**
 * `np.percentile(np.abs(np.diff(heights)), 75)` over the distance-sorted
 * profile: position `0.75·(n−1)` linearly interpolated between the two
 * neighbouring order statistics, using NumPy's `lerp` form `a + (b − a)·t`.
 */
function percentile75AbsHeightDiff(sorted: readonly ProfilePoint[]): number {
  const n = sorted.length - 1; // number of height differences
  const diffs = new Array<number>(n);
  for (let i = 1; i < sorted.length; i += 1) {
    diffs[i - 1] = Math.abs(sorted[i]!.h - sorted[i - 1]!.h);
  }
  diffs.sort((a, b) => a - b); // percentile works on order statistics
  const position = 0.75 * (n - 1);
  const lower = Math.floor(position);
  const upper = Math.ceil(position);
  const frac = position - lower;
  const lowerValue = diffs[lower]!;
  const upperValue = diffs[upper]!;
  return lowerValue + (upperValue - lowerValue) * frac;
}
